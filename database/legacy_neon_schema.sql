CREATE OR REPLACE FUNCTION hrflow_guard_payroll_item_snapshot()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    payroll_status VARCHAR(20);
BEGIN
    SELECT status
      INTO payroll_status
      FROM payroll_payroll
     WHERE id = COALESCE(NEW.payroll_id, OLD.payroll_id);

    IF payroll_status IN ('approved', 'paid') THEN
        RAISE EXCEPTION 'PayrollItem snapshots cannot change after payroll approval';
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_guard_payroll_item_snapshot ON payroll_payrollitem;
CREATE TRIGGER trg_guard_payroll_item_snapshot
BEFORE INSERT OR UPDATE OR DELETE ON payroll_payrollitem
FOR EACH ROW
EXECUTE FUNCTION hrflow_guard_payroll_item_snapshot();

CREATE OR REPLACE FUNCTION hrflow_validate_completed_payment()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    expected_net NUMERIC(14, 2);
    parent_status VARCHAR(20);
BEGIN
    SELECT item.net_salary, payroll.status
      INTO expected_net, parent_status
      FROM payroll_payrollitem AS item
      JOIN payroll_payroll AS payroll ON payroll.id = item.payroll_id
     WHERE item.id = NEW.payroll_item_id;

    IF parent_status <> 'approved' THEN
        RAISE EXCEPTION 'Payment requires an approved payroll';
    END IF;

    IF NEW.amount <> expected_net THEN
        RAISE EXCEPTION 'Payment amount must equal PayrollItem net salary';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_completed_payment ON payroll_payment;
CREATE TRIGGER trg_validate_completed_payment
BEFORE INSERT OR UPDATE ON payroll_payment
FOR EACH ROW
EXECUTE FUNCTION hrflow_validate_completed_payment();

