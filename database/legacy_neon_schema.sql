    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month SMALLINT NOT NULL,
    year SMALLINT NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    currency_code VARCHAR(3) NOT NULL,
    calculation_version VARCHAR(30) NOT NULL DEFAULT 'v1',
    status VARCHAR(20) NOT NULL DEFAULT 'draft',
    total_gross NUMERIC(16, 2) NOT NULL DEFAULT 0,
    total_deductions NUMERIC(16, 2) NOT NULL DEFAULT 0,
    total_net NUMERIC(16, 2) NOT NULL DEFAULT 0,
    created_by_id INTEGER NOT NULL
        REFERENCES public.auth_user(id) ON DELETE RESTRICT,
    reviewed_by_id INTEGER
        REFERENCES public.auth_user(id) ON DELETE SET NULL,
    approved_by_id INTEGER
        REFERENCES public.auth_user(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMPTZ,
    approved_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_payroll_month_year UNIQUE (month, year),
    CONSTRAINT ck_payroll_month CHECK (month BETWEEN 1 AND 12),
    CONSTRAINT ck_payroll_year CHECK (year BETWEEN 2000 AND 9999),
    CONSTRAINT ck_payroll_period CHECK (
        period_start = make_date(year, month, 1)
        AND period_end = (make_date(year, month, 1) + INTERVAL '1 month - 1 day')::date
    ),
    CONSTRAINT ck_payroll_currency CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_payroll_status CHECK (
        status IN ('draft', 'calculated', 'reviewed', 'approved', 'paid')
    ),
    CONSTRAINT ck_payroll_totals CHECK (
        total_gross >= 0 AND total_deductions >= 0 AND total_net >= 0
    )
);

